def create_riot_tls_context() -> ssl.SSLContext:
    """Return a TLS context that trusts Riot's game authority alone.

    The host name is not checked: both servers listen only on 127.0.0.1, so it would add nothing.
    What keeps an impostor out is the signature, which must chain to Riot's root.

    Returns:
        The context, for every connection to the game or the League client.
    """
    context = ssl.create_default_context(ssl.Purpose.SERVER_AUTH, cadata=RIOT_ROOT_CERTIFICATE_PEM)
    context.check_hostname = False
    context.verify_mode = ssl.CERT_REQUIRED
    return context
